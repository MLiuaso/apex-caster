package bitter.apexcaster.info.ui.theme

//[@AGENT][The palette lives in the MaterialTheme color scheme built in Theme.kt — define the
// concrete values there, not here, and never hardcode a Color anywhere in ui/. UI code must
// always read from MaterialTheme.colorScheme so the whole app can be recoloured from one place.
//
// Choose a palette that reads as athletic and performance-oriented: high contrast, confident,
// energetic. A restrained set of neutrals carrying the layout, with a strong accent reserved
// for the things that signal action and progress (primary buttons, the active navigation item,
// progress arcs and bars, live/running states). Light or dark is a per-app decision — commit
// to whichever suits the brand and make both schemes coherent if you support both.
//
// How the roles are used across this app (see Theme.kt for the full design language):
//  background / onBackground     — the screen itself and text drawn straight onto it.
//  surface / onSurface           — raised cards and panels, and their primary text.
//  surfaceVariant                — inset wells: icon circles, badges, chips, progress tracks.
//  onSurfaceVariant              — captions, labels, inactive icons, secondary copy.
//  primary / onPrimary           — the accent: filled primary buttons, the selected navigation
//                                  item, progress indicators, active/running emphasis.
//  outline / outlineVariant      — the hairline borders and gradient rules the design leans on.
//  error / onError               — destructive confirmation in delete dialogs.
// If you need a token this list does not cover, extend the color scheme rather than
// reintroducing standalone Color values in this file.]
